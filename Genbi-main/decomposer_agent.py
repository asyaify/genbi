class DecompositionOutput(BaseModel):
    reflections: str = Field(...)
    metrics: list[str] = Field(...)
    dimensions: list[str] = Field(...)
    filters: list[str] = Field(...)
    time_context: str = Field(...)


def decompose_query(user_query: str) -> dict:
    """
    Отправляет запрос пользователя Агенту-Декомпозитору и возвращает структурированный JSON.
    """
    logging.info(f"Декомпозиция запроса: '{user_query}'...")
    
    try:
        completion = client.chat.completions.create(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": DECOMPOSER_PROMPT},
                {"role": "user", "content": user_query}
            ],
            temperature=0.1,
            response_format = {  
                "type": "json_schema",
                "json_schema": {
                    "name": "decomposition", 
                    "strict": True,
                    "schema": DecompositionOutput.model_json_schema()
                },
            },
            timeout=30.0
        )
        
        response_text = completion.choices[0].message.content
        decomposed_data = json.loads(response_text)
        
        logging.info(json.dumps(decomposed_data, ensure_ascii=False, indent=2))
        return decomposed_data
        
    except json.JSONDecodeError as e:
        logging.error(f"❌ ОШИБКА парсинга JSON от декомпозитора: {e}")
        logging.error(f"Ответ модели: {response_text}")
        return {}
    except Exception as e:
        logging.error(f"❌ ОШИБКА при вызове LLM: {e}")
        return {}

